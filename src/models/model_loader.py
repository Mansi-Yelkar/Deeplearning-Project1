from dataclasses import dataclass
from typing import List, Optional

@dataclass
class Detection:
    """Represents a single bounding box detection from the object detection model."""
    class_id: int
    class_name: str
    confidence: float
    box: List[float]  # [x1, y1, x2, y2] in pixel coordinates
    track_id: Optional[int] = None

    @property
    def x1(self) -> float:
        return self.box[0]

    @property
    def y1(self) -> float:
        return self.box[1]

    @property
    def x2(self) -> float:
        return self.box[2]

    @property
    def y2(self) -> float:
        return self.box[3]

    @property
    def width(self) -> float:
        return self.x2 - self.x1

    @property
    def height(self) -> float:
        return self.y2 - self.y1

    @property
    def center(self) -> tuple[float, float]:
        return ((self.x1 + self.x2) / 2.0, (self.y1 + self.y2) / 2.0)

    @property
    def area(self) -> float:
        return max(0.0, self.width) * max(0.0, self.height)
